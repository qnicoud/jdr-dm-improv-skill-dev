/**
 * Jeu de couleurs d'une palette statique (D53). [ThemePalette.DYNAMIC] n'en a pas : ses couleurs viennent
 * du téléphone (voir [DmGymTheme]). Les contrastes de chaque jeu sont vérifiés par `ContrastTest`.
 */
fun staticColorScheme(
    palette: ThemePalette,
    dark: Boolean,
): ColorScheme =
    when (palette) {
        ThemePalette.PARCHMENT -> if (dark) DarkColors else LightColors
        ThemePalette.FOREST -> if (dark) ForestDark else ForestLight
        ThemePalette.NIGHT -> if (dark) NightDark else NightLight
        ThemePalette.MIST -> if (dark) MistDark else MistLight
        ThemePalette.DYNAMIC -> error("DYNAMIC has no static color scheme")
    }

